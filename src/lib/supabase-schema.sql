-- ============================================================
-- Migration: Speed Arena 改用 Realtime Broadcast（2026-08-12）
-- ============================================================
-- postgres_changes 收唔到（Realtime WAL 層面問題），改用官方推薦嘅
-- Broadcast + database trigger 方案。用 public broadcast（private: false）
-- 因為網站冇登入系統（anon key 無法通過 private channel 授權）。
-- 已驗證 client-to-client broadcast 正常（PONG 測試）。
-- 喺 Supabase SQL Editor 執行：

CREATE OR REPLACE FUNCTION public.broadcast_speed_room_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
  room_id_val bigint;
  payload jsonb;
BEGIN
  -- speed_rooms 自己就係 room（id），其他表先有 room_id 欄位
  IF TG_TABLE_NAME = 'speed_rooms' THEN
    room_id_val := COALESCE(NEW.id, OLD.id);
  ELSE
    room_id_val := COALESCE(NEW.room_id, OLD.room_id);
  END IF;
  payload := jsonb_build_object(
    'table', TG_TABLE_NAME,
    'operation', TG_OP,
    'row', CASE WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END
  );
  PERFORM realtime.send(payload, 'room-change', 'room:' || room_id_val || ':updates', false);
  RETURN COALESCE(NEW, OLD);
END;
$$;

CREATE TRIGGER trg_speed_rooms_broadcast
AFTER INSERT OR UPDATE ON public.speed_rooms
FOR EACH ROW EXECUTE FUNCTION public.broadcast_speed_room_change();

CREATE TRIGGER trg_speed_players_broadcast
AFTER INSERT OR UPDATE ON public.speed_players
FOR EACH ROW EXECUTE FUNCTION public.broadcast_speed_room_change();

CREATE TRIGGER trg_speed_answers_broadcast
AFTER INSERT OR UPDATE ON public.speed_answers
FOR EACH ROW EXECUTE FUNCTION public.broadcast_speed_room_change();


