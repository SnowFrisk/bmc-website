-- ============================================================
-- Migration: Speed Arena 實時對戰（2026-08-11）
-- ============================================================
-- Kahoot-style real-time battle. 狀態機全部由 DB 驅動，
-- 透過 Supabase Realtime (postgres_changes) 廣播。
--   1. Host create room → players join with the 6-digit code
--   2. Host advances questions via question_data JSONB
--   3. Players insert answers; Host tallies scores
-- 喺 Supabase SQL Editor 執行：

CREATE TABLE IF NOT EXISTS speed_rooms (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT UNIQUE NOT NULL,                -- 6 位 join code
  status TEXT NOT NULL DEFAULT 'waiting',   -- waiting / playing / ended
  current_question INT NOT NULL DEFAULT 0,  -- 0 = 未開始
  question_data JSONB,                      -- { text, options, correct, timeLimit }
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS speed_players (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id BIGINT REFERENCES speed_rooms(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  score INT NOT NULL DEFAULT 0,
  joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS speed_answers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id BIGINT REFERENCES speed_rooms(id) ON DELETE CASCADE,
  player_id BIGINT REFERENCES speed_players(id) ON DELETE CASCADE,
  question_index INT NOT NULL,
  is_correct BOOLEAN NOT NULL,
  answered_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE speed_rooms   ENABLE ROW LEVEL SECURITY;
ALTER TABLE speed_players ENABLE ROW LEVEL SECURITY;
ALTER TABLE speed_answers ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public read speed_rooms"   ON speed_rooms   FOR SELECT USING (true);
CREATE POLICY "Public insert speed_rooms" ON speed_rooms   FOR INSERT WITH CHECK (true);
CREATE POLICY "Public update speed_rooms" ON speed_rooms   FOR UPDATE USING (true);
CREATE POLICY "Public read speed_players"   ON speed_players   FOR SELECT USING (true);
CREATE POLICY "Public insert speed_players" ON speed_players   FOR INSERT WITH CHECK (true);
CREATE POLICY "Public update speed_players" ON speed_players   FOR UPDATE USING (true);
CREATE POLICY "Public read speed_answers"   ON speed_answers   FOR SELECT USING (true);
