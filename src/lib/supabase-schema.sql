-- ── 1. problems ─────────────────────────────────────────────
-- Each row represents one difficulty tier of one cycle.
-- cycle_number groups the three tiers together.

-- Each row is a 大題 (parent_id NULL) or one 步驟 of it (parent_id set).
-- cycle_number groups the main problem + its steps together.
-- points: custom per-step score; NULL falls back to difficulty_levels.points.
CREATE TABLE IF NOT EXISTS problems (
  id                   BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_number         INT          NOT NULL,
  difficulty_level_id  INT          REFERENCES difficulty_levels(id),  -- NULL for 大題
  points               INT,                                             -- 自訂分數，NULL = 用 difficulty_levels
  title                TEXT         NOT NULL,
  latex                TEXT         NOT NULL,
  solution             TEXT,
  start_date           TIMESTAMPTZ,
  end_date             TIMESTAMPTZ,
  is_active            BOOLEAN      NOT NULL DEFAULT false,
  created_at           TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

